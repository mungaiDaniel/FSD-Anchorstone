from datetime import datetime, timezone

from sqlalchemy import Boolean, Column, DateTime, Integer, String, Text

from app.database.database import db
from base_model import Base


class ReportSchedule(Base, db.Model):
    """Singleton (id 1): the monthly AUM summary email. On the 1st of each month
    the scheduler generates it for the month just ended and holds one email per
    recipient as "Awaiting confirmation" until an admin confirms or suppresses it."""

    __tablename__ = "report_schedule"

    id = Column(Integer, primary_key=True)
    aum_enabled = Column(Boolean, nullable=False, default=False, server_default="false")
    aum_recipients = Column(Text, nullable=True)  # comma-separated addresses
    # The month ("YYYY-MM") last generated by the schedule, so a restart on the
    # 1st (or a second worker) never generates it twice.
    aum_last_month = Column(String(7), nullable=True)
    aum_last_run_at = Column(DateTime(timezone=True), nullable=True)
    updated_at = Column(DateTime(timezone=True), nullable=True,
                        onupdate=lambda: datetime.now(timezone.utc))
    updated_by = Column(String(120), nullable=True)

    @classmethod
    def get(cls, session, lock: bool = False) -> "ReportSchedule":
        q = session.query(cls).filter(cls.id == 1)
        row = (q.with_for_update() if lock else q).first()
        if row is None:
            row = cls(id=1)
            session.add(row)
            session.flush()
        return row

    @property
    def recipients(self) -> list[str]:
        return [r.strip() for r in (self.aum_recipients or "").split(",") if r.strip()]

    def to_dict(self) -> dict:
        from app.utils.dates import iso

        return {
            "aum_enabled": self.aum_enabled,
            "aum_recipients": self.recipients,
            "aum_last_month": self.aum_last_month,
            "aum_last_run_at": iso(self.aum_last_run_at),
            "updated_by": self.updated_by,
        }
