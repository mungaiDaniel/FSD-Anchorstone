import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import { toast } from "sonner";
import { Card, Field } from "@/components/ui/Page";
import { reportService } from "@/services";
import type { ReportSchedule } from "@/lib/types";
import { ROUTES } from "@/lib/constants";
import { apiErrorMessage, formatDateTime } from "@/lib/utils";

/** Super admin: the one scheduled report — the monthly AUM summary email. */
export default function ScheduledReportsSection() {
  const navigate = useNavigate();
  const [schedule, setSchedule] = useState<ReportSchedule | null>(null);
  const [enabled, setEnabled] = useState(false);
  const [recipients, setRecipients] = useState("");
  const [saving, setSaving] = useState(false);
  const [running, setRunning] = useState(false);

  const apply = (s: ReportSchedule) => {
    setSchedule(s);
    setEnabled(s.aum_enabled);
    setRecipients(s.aum_recipients.join(", "));
  };

  useEffect(() => {
    reportService.getSchedule().then(apply).catch((err) => toast.error(apiErrorMessage(err)));
  }, []);

  const list = recipients.split(/[,\s;]+/).map((r) => r.trim()).filter(Boolean);
  const dirty = !!schedule && (enabled !== schedule.aum_enabled || list.join(",") !== schedule.aum_recipients.join(","));

  const save = async () => {
    setSaving(true);
    try {
      const res = await reportService.saveSchedule({ aum_enabled: enabled, aum_recipients: list });
      apply(res.data!);
      toast.success(res.message);
    } catch (err) {
      toast.error(apiErrorMessage(err));
    } finally {
      setSaving(false);
    }
  };

  const runNow = async () => {
    setRunning(true);
    try {
      const res = await reportService.runScheduleNow();
      toast.success(res.message, {
        action: { label: "Open Emails", onClick: () => navigate(`${ROUTES.EMAILS}?status=pending`) },
      });
    } catch (err) {
      toast.error(apiErrorMessage(err));
    } finally {
      setRunning(false);
    }
  };

  return (
    <Card title="Scheduled reports" className="mb-3">
      <p style={{ fontSize: 13.5, color: "var(--color-text-secondary)" }}>
        <strong style={{ color: "var(--color-text-primary)" }}>Monthly AUM summary.</strong> On the 1st of each month at
        07:00 (Nairobi), the portfolio summary for the month just ended is generated as an Excel attachment and added to the
        Emails page as <strong>Awaiting confirmation</strong>, one email per recipient. An admin confirms or suppresses it
        before it is sent.
      </p>
      {!schedule ? (
        <p style={{ fontSize: 13, color: "var(--color-text-tertiary)" }}>Loading…</p>
      ) : (
        <>
          <label className="d-flex align-items-center gap-2 mb-3" style={{ fontSize: 14, cursor: "pointer" }}>
            <input type="checkbox" className="form-check-input m-0" checked={enabled} onChange={(e) => setEnabled(e.target.checked)} />
            Generate the monthly AUM summary automatically
          </label>
          <Field label="Recipients" hint="Email addresses, separated by commas. Up to 20.">
            <textarea className="form-control" rows={2} value={recipients} onChange={(e) => setRecipients(e.target.value)}
              placeholder="md@anchorstone.co.ke, finance@anchorstone.co.ke" />
          </Field>
          <p style={{ fontSize: 12, color: "var(--color-text-tertiary)" }}>
            {schedule.aum_last_month
              ? `Last generated by the schedule for ${schedule.aum_last_month} on ${formatDateTime(schedule.aum_last_run_at)}.`
              : "Not generated by the schedule yet."}
          </p>
          <div className="d-flex flex-wrap gap-2">
            <button className="btn btn-primary btn-sm" onClick={save} disabled={saving || !dirty}>
              {saving ? "Saving…" : "Save"}
            </button>
            <button className="btn btn-outline-secondary btn-sm" onClick={runNow} disabled={running || dirty || !schedule.aum_recipients.length}
              title={dirty ? "Save your changes first" : undefined}>
              {running ? "Generating…" : "Generate last month's summary now"}
            </button>
          </div>
        </>
      )}
    </Card>
  );
}
